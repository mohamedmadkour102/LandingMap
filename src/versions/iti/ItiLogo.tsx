type Tone = 'color' | 'white'
type Layout = 'vertical' | 'horizontal' | 'icon'

function Icon({ tone }: { tone: Tone }) {
  const roof = tone === 'white' ? '#fff' : STEEL
  const pillar = tone === 'white' ? '#fff' : NAVY
  return (
    <>
      <polygon fill={roof} points={ICON_ROOF} />
      <polygon fill={pillar} points={ICON_PILLAR_R} />
      <polygon fill={pillar} points={ICON_PILLAR_L} />
    </>
  )
}

function Words({ tone, descriptor }: { tone: Tone; descriptor: boolean }) {
  const fill = tone === 'white' ? '#fff' : NAVY
  return (
    <g fill={fill}>
      {WORDMARK.map((d) => (
        <path key={d.slice(0, 18)} d={d} />
      ))}
      {descriptor && DESCRIPTOR.map((d, i) => <path key={i} d={d} />)}
    </g>
  )
}

interface Props {
  tone?: Tone
  layout?: Layout
  /** Hide "Inversiones en Tecnología Industrial" at small sizes (simplified logo, guideline p.16) */
  descriptor?: boolean
  className?: string
  title?: string
}

export default function ItiLogo({
  tone = 'color',
  layout = 'horizontal',
  descriptor = true,
  className,
  title = 'ITI Group',
}: Props) {
  if (layout === 'icon') {
    return (
      <svg viewBox="131 0 660 811" className={className} role="img" aria-label={title}>
        <Icon tone={tone} />
      </svg>
    )
  }

  if (layout === 'vertical') {
    const h = descriptor ? 1084 : 1004
    return (
      <svg viewBox={`-1 0 926 ${h}`} className={className} role="img" aria-label={title}>
        <Icon tone={tone} />
        <Words tone={tone} descriptor={descriptor} />
      </svg>
    )
  }

  // Horizontal: icon left, wordmark right, 1X gap (guideline p.11)
  const textTop = 873
  const textH = descriptor ? 211 : 131
  const iconScale = (textH * 1.5) / 811
  const iconH = 811 * iconScale
  const iconW = 659 * iconScale
  const gap = iconW * 0.3
  const textX = iconW + gap
  const textY = (iconH - textH) / 2 - textTop
  return (
    <svg
      viewBox={`0 0 ${textX + 925} ${iconH}`}
      className={className}
      role="img"
      aria-label={title}
    >
      <g transform={`scale(${iconScale}) translate(-131.79 0)`}>
        <Icon tone={tone} />
      </g>
      <g transform={`translate(${textX + 0.31} ${textY})`}>
        <Words tone={tone} descriptor={descriptor} />
      </g>
    </svg>
  )
}

